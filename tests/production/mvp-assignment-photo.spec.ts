import {expect,test} from '@playwright/test'
import {browserControl} from '../e2e/support/browser-ui'
test.use({trace:'off',screenshot:'off',video:'off'})

test('MVP: assignment photo capture, encrypted sync and scoped Browser with Viewer return',async({page})=>{
  test.setTimeout(120000)
  await page.goto('/welcome/create')
  await page.getByRole('button',{name:'Создать Recovery Key'}).click()
  await page.getByText('Я сохранил Recovery Key отдельно от устройства.').click()
  await page.getByTestId('welcome-finish').click()
  await expect(page).toHaveURL(/\/assignments$/)
  await page.getByRole('button',{name:'Создать задание',exact:true}).click()
  await page.locator('#assignment-title').fill('MVP assigned photograph')
  await page.getByRole('button',{name:'Создать зашифрованное задание'}).click()
  const card=page.locator('[data-testid^="assignment-card-"]').filter({hasText:'MVP assigned photograph'})
  await expect(card).toBeVisible()
  await page.getByRole('button',{name:'Синхронизировать',exact:true}).click()
  await expect(card.getByText('Активно',{exact:true})).toBeVisible()
  const assignmentId=(await card.getAttribute('data-testid'))!.slice('assignment-card-'.length)
  await card.getByTestId('assignment-capture-'+assignmentId).click()
  await expect.poll(()=>page.locator('video').evaluate(el=>(el as HTMLVideoElement).videoWidth)).toBeGreaterThan(0)
  await page.getByRole('button',{name:'Сделать снимок'}).click()
  await expect(page.getByText(/Зашифровано и сохранено локально/)).toBeVisible()
  await page.getByRole('link',{name:'Browser',exact:true}).click()
  await browserControl(page,'Синхронизировать')
  await expect(page.locator('.photo-row')).toHaveAttribute('data-sync-state','synced')
  // A personal photograph must not appear in the assignment's Browser.
  await page.getByRole('link',{name:'Камера',exact:true}).click()
  await expect.poll(()=>page.locator('video').evaluate(el=>(el as HTMLVideoElement).videoWidth)).toBeGreaterThan(0)
  await page.getByRole('button',{name:'Сделать снимок'}).click()
  await expect(page.getByText(/Зашифровано и сохранено локально/)).toBeVisible()
  await page.getByRole('link',{name:'Browser',exact:true}).click()
  await expect(page.locator('.photo-row')).toHaveCount(2)
  await page.goto('/assignments')
  await page.getByTestId('assignment-browser-'+assignmentId).click()
  await expect(page.getByTestId('browser-assignment-scope')).toContainText(assignmentId.slice(0,8))
  await expect(page.locator('.photo-row')).toHaveCount(1)
  await page.locator('.photo-row').getByTestId('browser-file-menu-toggle').click()
  await page.locator('.photo-row').getByRole('link',{name:/Полный просмотр файла/}).click()
  await expect(page.getByTestId('file-viewer-image')).toBeVisible()
  await page.getByRole('link',{name:'В Browser',exact:true}).click()
  await expect(page.getByTestId('browser-assignment-scope')).toContainText(assignmentId.slice(0,8))
  await expect(page.locator('.photo-row')).toHaveCount(1)
  await page.reload()
  await expect(page.locator('.photo-row')).toHaveCount(1)
  await page.getByTestId('browser-tab-active').click()
  await expect(page.locator('.photo-row')).toHaveCount(2)
  await expect(page).not.toHaveURL(/assignmentId=/)
})
