import {expect,test,type Page} from '@playwright/test'
import {browserControl} from '../e2e/support/browser-ui'
test.use({trace:'off',screenshot:'off',video:'off'})

// UI-only smoke of the actual compiled app and live API. No source imports,
// synthetic server responses, screenshots or production database resets.
test('MVP: encrypted photo assignment, contacts, team invitation and notification delivery',async({browser})=>{
  test.setTimeout(180000)
  const ownerContext=await browser.newContext(),recipientContext=await browser.newContext()
  const owner=await ownerContext.newPage(),recipient=await recipientContext.newPage()
  async function enroll(page:Page):Promise<string>{
    await page.goto('/welcome/create')
    await page.getByRole('button',{name:'Создать Recovery Key'}).click()
    await page.getByText('Я сохранил Recovery Key отдельно от устройства.').click()
    await page.getByTestId('welcome-finish').click()
    await expect(page).toHaveURL(/\/assignments$/)
    await page.goto('/settings')
    await expect(page.locator('[data-testid="shell-status-link"][data-session-state="online"]')).toBeVisible()
    const id=await page.locator('.foundation-card').filter({hasText:'Аккаунт:'}).locator('code').first().textContent()
    expect(id).toMatch(/^[a-f0-9-]{36}$/)
    return id!.trim()
  }
  async function addContact(page:Page,id:string,name:string):Promise<void>{
    await page.goto('/contacts')
    await page.getByTestId('contacts-lookup-id').fill(id)
    await page.getByRole('button',{name:'Проверить ключ',exact:true}).click()
    await page.getByTestId('contacts-fingerprint-ack').check()
    await page.getByRole('button',{name:'Подтвердить отпечаток',exact:true}).click()
    await expect(page.getByText('Ключ подтверждён на этом устройстве.')).toBeVisible()
    await page.getByTestId('contacts-alias').fill(name)
    await page.getByRole('button',{name:'Добавить в контакты',exact:true}).click()
    await expect(page.getByTestId('contacts-row-'+id)).toContainText(name)
  }
  try{
    const ownerId=await enroll(owner),recipientId=await enroll(recipient)
    await addContact(owner,recipientId,'MVP photographer')
    await addContact(recipient,ownerId,'MVP coordinator')
    // Device-local contact settings survive a real page reload.
    await owner.getByRole('button',{name:'Карточка',exact:true}).click()
    await owner.getByLabel('Локальное имя', {exact:true}).fill('MVP updated photographer')
    await owner.getByRole('button',{name:'Сохранить имя'}).click()
    await expect(owner.getByText('Локальное имя обновлено.',{exact:true})).toBeVisible()
    await owner.reload()
    await expect(owner.getByTestId('contacts-row-'+recipientId)).toContainText('MVP updated photographer')

    await owner.goto('/assignments')
    await owner.getByRole('button',{name:'Создать задание',exact:true}).click()
    await owner.locator('#assignment-title').fill('MVP photo assignment')
    await owner.locator('#assignment-instructions').fill('Photograph the entrance')
    await owner.getByRole('button',{name:'Файлы',exact:true}).click()
    await owner.locator('#assignment-goal').fill('2')
    await owner.locator('[name="photoShots"]').fill('Front entrance\nSide entrance')
    await owner.getByRole('button',{name:'Создать зашифрованное задание'}).click()
    const card=owner.locator('[data-testid^="assignment-card-"]').filter({hasText:'MVP photo assignment'})
    await expect(card).toBeVisible()
    await owner.getByRole('button',{name:'Синхронизировать',exact:true}).click()
    await expect(card.getByText('Активно',{exact:true})).toBeVisible()
    await card.getByRole('button',{name:'Открыть',exact:true}).click()
    await owner.getByTestId('open-fieldwork-editor').click()
    const editorPath=new URL(owner.url()).pathname
    await owner.getByRole('tab',{name:'Файлы',exact:true}).click()
    await expect(owner.getByTestId('editor-photo-instructions')).toHaveValue('Front entrance\nSide entrance')
    await owner.reload()
    await owner.getByRole('tab',{name:'Участники',exact:true}).click()
    await owner.locator('#editor-recipient-id').fill(recipientId)
    await owner.getByRole('button',{name:'Проверить ключ исполнителя'}).click()
    await owner.getByRole('button',{name:'Отправить подписанное приглашение'}).click()
    await expect(owner.locator('[data-testid^="editor-participant-"]')).toHaveCount(1)

    await recipient.goto('/notifications')
    const assignmentNotice=recipient.locator('.notification-summary').filter({hasText:'Приглашение в задание'})
    await expect(assignmentNotice).toBeVisible()
    await assignmentNotice.click()
    await recipient.getByTestId('notification-open').click()
    await expect(recipient).toHaveURL(/\/assignments$/)
    await recipient.getByRole('button',{name:'Ключ владельца',exact:true}).click()
    await recipient.getByRole('button',{name:'Принять задание'}).click()
    const recipientCard=recipient.locator('[data-testid^="assignment-card-"]').filter({hasText:'MVP photo assignment'})
    await expect(recipientCard).toBeVisible()
    await recipientCard.getByRole('link',{name:'Снимать',exact:true}).click()
    await expect.poll(()=>recipient.locator('video').evaluate(el=>(el as HTMLVideoElement).videoWidth)).toBeGreaterThan(0)
    await recipient.getByRole('button',{name:'Сделать снимок'}).click()
    await expect(recipient.getByText(/Зашифровано и сохранено локально/)).toBeVisible()
    await recipient.getByRole('link',{name:'Browser',exact:true}).click()
    await browserControl(recipient,'Синхронизировать')
    await expect(recipient.locator('.photo-row')).toHaveAttribute('data-sync-state','synced')
    await recipient.goto('/assignments')
    await recipientCard.getByRole('button',{name:'Открыть',exact:true}).click()
    await recipient.getByRole('button',{name:'Проверить ключ владельца',exact:true}).click()
    await recipient.getByRole('button',{name:'Отправить в задание',exact:true}).click()
    await expect(recipient.getByText('Зашифрованный grant и отправка задания поставлены в очередь')).toBeVisible()
    await owner.goto('/assignments')
    const received=owner.locator('[data-testid^="assignment-card-"]').filter({hasText:'MVP photo assignment'})
    await expect(received.getByTestId('assignment-media-photo')).toContainText('1 / 2')
    await received.getByRole('button',{name:'Открыть',exact:true}).click()
    await owner.getByRole('button',{name:'Просмотр',exact:true}).click()
    await expect(owner.locator('img.decrypted-preview')).toBeVisible()

    await owner.goto('/contacts')
    await owner.getByRole('button',{name:/^Команды \(/}).click()
    await owner.getByRole('button',{name:'Создать команду',exact:true}).click()
    await owner.getByTestId('team-name').fill('MVP field team')
    await owner.getByLabel('Описание',{exact:true}).fill('Photo team')
    await owner.getByTestId('team-create-submit').click()
    const team=owner.getByTestId(/^team-row-/).filter({hasText:'MVP field team'})
    await team.getByTestId(/^team-open-/).click()
    await expect(owner.getByTestId('team-profile-delivery')).toContainText('Подтверждено сервером')
    await owner.getByTestId('team-profile-settings').click()
    await owner.getByRole('button',{name:'Добавить участника',exact:true}).click()
    await owner.getByTestId('team-invite-contact').selectOption(recipientId)
    await owner.getByTestId('team-invite-submit').click()

    await recipient.goto('/notifications')
    const teamNotice=recipient.locator('.notification-summary').filter({hasText:'Приглашение в команду'})
    await expect(teamNotice).toBeVisible()
    await teamNotice.click()
    await recipient.getByTestId('notification-open').click()
    await expect(recipient).toHaveURL(/\/contacts$/)
    await recipient.getByRole('button',{name:/^Команды \(/}).click()
    await recipient.getByTestId('team-incoming-invites').getByRole('button',{name:'Принять',exact:true}).click()
    await expect(recipient.getByTestId('team-joined-list')).toContainText('MVP field team')

    await recipient.goto('/notifications/settings')
    await recipient.getByTestId('notification-setting-newFiles').uncheck()
    await recipient.getByTestId('notification-settings-save').click()
    await expect(recipient.getByText('Сохранено в зашифрованном хранилище этого устройства.',{exact:true})).toBeVisible()
    await recipient.reload()
    await expect(recipient.getByTestId('notification-setting-newFiles')).not.toBeChecked()
    await recipient.goto('/notifications')
    await recipient.getByTestId('notifications-mark-all').click()
    await expect(recipient.getByTestId('notifications-mark-all')).toBeDisabled()
    await recipient.getByTestId('notifications-unread').click()
    await expect(recipient.getByTestId('notifications-empty')).toContainText('Непрочитанных уведомлений нет.')
    // Encrypted details are still readable on the owner's independent route.
    await owner.goto(editorPath)
    await owner.getByRole('tab',{name:'Файлы',exact:true}).click()
    await expect(owner.getByTestId('editor-photo-instructions')).toHaveValue('Front entrance\nSide entrance')
  }finally{await ownerContext.close();await recipientContext.close()}
})
