import {test,expect} from '@playwright/test'

test('PIN: genuine enrollment → change length → reload rejects old PIN → authenticated delay → disable',async({page})=>{
  test.setTimeout(210000)
  const enter=async(code:string)=>{for(const digit of code)await page.getByRole('button',{name:'Цифра '+digit}).click()}
  await page.goto('/settings');await page.getByRole('button',{name:'Создать ключ'}).click()
  const recovery=await page.locator('#generated-key').inputValue()
  await page.getByLabel('Я сохранил ключ восстановления').check();await page.getByRole('button',{name:'Завершить регистрацию'}).click()
  await expect(page.getByText('Подтверждённая сессия')).toBeVisible()
  await page.goto('/settings/security');await page.getByTestId('security-pin-create').click()
  await page.getByTestId('security-pin-new').fill('4826');await page.getByTestId('security-pin-repeat').fill('4826')
  await page.getByTestId('security-pin-recovery').fill(recovery);await page.getByTestId('security-pin-ack').check();await page.getByTestId('security-pin-save').click()
  await expect(page.getByRole('heading',{name:'Введите PIN'})).toBeVisible();await enter('4826')
  await expect(page.getByTestId('security-pin-change')).toBeVisible();await page.getByTestId('security-pin-change').click()
  await page.getByTestId('security-pin-current').fill('4826');await page.getByTestId('security-pin-changed').fill('13579');await page.getByTestId('security-pin-changed-repeat').fill('13579')
  await page.getByTestId('security-pin-settings-ack').check();await page.getByTestId('security-pin-settings-save').click()
  await expect(page.getByRole('heading',{name:'Введите PIN'})).toBeVisible()
  await expect(page.locator('.pin-indicators span')).toHaveCount(5)
  await page.reload();await expect(page.getByRole('heading',{name:'Введите PIN'})).toBeVisible()
  await enter('48260');await expect(page.getByText('Неверный PIN')).toBeVisible();await expect(page.locator('.shell-main')).toHaveCount(0)
  await enter('13579');await expect(page.getByTestId('security-pin-disable')).toBeVisible()
  await page.getByRole('slider',{name:'Через какое время запрашивать PIN'}).fill('2')
  await page.getByTestId('security-pin-current').fill('13579');await page.getByTestId('security-pin-settings-ack').check();await page.getByTestId('security-pin-settings-save').click()
  await expect(page.getByRole('heading',{name:'Введите PIN'})).toBeVisible();await enter('13579')
  await expect(page.locator('.pin-relock output')).toHaveText('2 мин')
  await page.getByTestId('security-pin-disable').click();await page.getByTestId('security-pin-current').fill('13579')
  await page.getByTestId('security-pin-settings-ack').check();await page.getByTestId('security-pin-settings-save').click()
  await expect(page.getByTestId('security-pin-create')).toBeVisible({timeout:30000})
  await page.reload();await expect(page.getByTestId('security-pin-create')).toBeVisible()
  await expect(page.locator('.pin-screen')).toHaveCount(0)
})
