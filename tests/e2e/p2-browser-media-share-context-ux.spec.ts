import {expect,test} from '@playwright/test'

test('Browser v3: video/audio share uses a scoped E2EE panel without issuing grants',async({page,context})=>{
  test.setTimeout(120000)
  await page.setViewportSize({width:390,height:844})
  await page.goto('/settings')
  await page.getByRole('button',{name:'Создать ключ'}).click()
  await page.getByLabel('Я сохранил ключ восстановления').check()
  await page.getByRole('button',{name:'Завершить регистрацию'}).click()
  await expect(page.getByText('Подтверждённая сессия')).toBeVisible()
  await page.goto('/browser')
  await context.setOffline(true)
  const picker=page.getByTestId('media-import-file')
  await picker.setInputFiles([
    {name:'PRIVATE-CONTEXT-A.wav',mimeType:'audio/wav',buffer:Buffer.alloc(8192,0x41)},
    {name:'PRIVATE-CONTEXT-B.webm',mimeType:'video/webm',buffer:Buffer.alloc(8192,0x42)},
  ])
  const rows=page.locator('[data-testid^="browser-row-media:"]')
  await expect(rows).toHaveCount(2,{timeout:30000})
  const selected=rows.first()
  const selectedId=(await selected.getAttribute('data-testid'))!.slice('browser-row-media:'.length)
  const toggle=selected.getByTestId('browser-file-menu-toggle')
  await toggle.click()
  await selected.getByTestId('browser-media-share-action').click()
  const sheet=page.getByTestId('browser-media-share-sheet')
  await expect(sheet).toBeVisible()
  await expect(sheet).toHaveAttribute('aria-modal','true')
  await expect(page.getByTestId('browser-media-share-close')).toBeFocused()
  await expect(sheet.getByTestId('browser-media-share-selected')).toContainText(selectedId.slice(0,8))
  await expect(sheet.getByTestId('media-share-panel')).toHaveCount(1)
  // This scoped sheet cannot expose other locally encrypted media.
  await expect(sheet.getByTestId('media-safe-candidate')).toHaveCount(0)
  await expect(sheet.getByRole('button',{name:'Проверить получателя медиа'})).toBeVisible()
  // No new grant or public URL is generated by opening a presentation sheet.
  const grants=await page.evaluate(async()=>{
    const x=await import('/src/features/media/application/media-grants.ts')
    return (await x.listOutgoingMediaGrants()).length
  })
  expect(grants).toBe(0)
  await page.getByTestId('browser-media-share-close').press('Escape')
  await expect(sheet).toHaveCount(0)
  await expect(toggle).toBeFocused()
  // Legacy incoming/receipt panel remains available until a separate
  // approved incoming-files destination replaces it.
  await expect(page.getByTestId('media-share-panel')).toHaveCount(1)
})