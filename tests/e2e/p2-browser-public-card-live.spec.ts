import {browserControl} from './support/browser-ui'
import {test,expect} from '@playwright/test'

test('Public Card: real camera → safe encrypted Garage publication → anonymous read → reload → revoke',async({browser})=>{
  test.setTimeout(180000)
  const owner=await browser.newContext({permissions:['camera']}),visitor=await browser.newContext(),recoveredOwner=await browser.newContext()
  const page=await owner.newPage(),external=await visitor.newPage()
  try{
    await page.goto('/settings')
    await page.getByRole('button',{name:'Создать ключ'}).click()
    const recoveryKey=await page.locator('#generated-key').inputValue()
    await page.getByLabel('Я сохранил ключ восстановления').check()
    await page.getByRole('button',{name:'Завершить регистрацию'}).click()
    await expect(page.locator('[data-testid="shell-status-link"][data-session-state="online"]')).toBeVisible()
    await page.getByRole('link',{name:'Камера',exact:true}).click()
    await expect.poll(()=>page.locator('video').evaluate(el=>(el as HTMLVideoElement).videoWidth)).toBeGreaterThan(0)
    await page.getByRole('button',{name:'Сделать снимок'}).click()
    await expect(page.getByText(/Зашифровано и сохранено локально/)).toBeVisible()
    await page.getByRole('link',{name:'Browser',exact:true}).click()
    await browserControl(page,'Синхронизировать')
    await expect(page.locator('.photo-row').first()).toHaveAttribute('data-sync-state','synced',{timeout:30000})
    await page.locator('.photo-row').first().getByTestId('browser-file-menu-toggle').click()
    await page.locator('.photo-row').first().getByRole('link',{name:/Полный просмотр файла/}).click()
    await expect(page.getByTestId('file-viewer-image')).toBeVisible()
    const viewerPath=new URL(page.url()).pathname
    await page.getByRole('button',{name:'На весь экран'}).click()
    const full=page.getByTestId('photo-fullscreen')
    await expect(full).toBeVisible()
    await expect(full.getByTestId('photo-fullscreen-image')).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(full).toHaveCount(0)
    await expect(page.getByRole('button',{name:'На весь экран'})).toBeFocused()
    await page.getByTestId('viewer-action-publish').click()
    await expect(page.getByTestId('public-card-publication').locator('img')).toBeVisible()
    await expect(page.getByTestId('public-card-publish')).toBeDisabled()
    await page.getByTestId('public-card-publication').locator('textarea').fill('Разрешённое публичное описание. '.repeat(45))
    await page.getByTestId('public-card-publish-review').check()
    await page.getByTestId('public-card-publish').click()
    const address=page.getByTestId('public-card-published-url')
    await expect(address).toHaveValue(/\/p\/[A-Za-z0-9_-]{43}#key=[A-Za-z0-9_-]{43}/,{timeout:30000})
    const url=await address.inputValue()
    const requestPaths:string[]=[]
    external.on('request',r=>{if(r.url().includes('/identity/')||r.url().includes('/public-cards/'))requestPaths.push(new URL(r.url()).pathname)})
    await external.goto(url)
    await expect(external.getByTestId('public-card-image')).toBeVisible()
    expect(requestPaths.filter(p=>p.startsWith('/identity/'))).toEqual([])
    await expect(external.locator('.shell-header,.shell-dock,.pin-screen')).toHaveCount(0)
    await expect(external.getByRole('button',{name:'Скачать безопасную копию'})).toBeDisabled()
    await external.locator('.bottom-brand').scrollIntoViewIfNeeded()
    await expect(external.locator('.bottom-brand')).toBeInViewport()
    expect(await external.locator('.public-page').evaluate(el=>el.scrollHeight>el.clientHeight)).toBe(true)
    await external.reload();await expect(external.getByTestId('public-card-image')).toBeVisible()
    await external.goto(url.split('#')[0]!)
    await expect(external.getByRole('heading',{name:'Карточка недоступна'})).toBeVisible()
    await expect(external.locator('main img')).toHaveCount(0)
    await external.goto(url.slice(0,-1)+(url.endsWith('A')?'B':'A'))
    await expect(external.getByRole('heading',{name:'Карточка недоступна'})).toBeVisible()
    await external.goto(url);await expect(external.getByTestId('public-card-image')).toBeVisible()
    // A genuine independent Recovery Key device can recover the encrypted
    // owner capability and revoke the same publication without the old IDB.
    const recovered=await recoveredOwner.newPage()
    await recovered.goto('/settings');await recovered.locator('#recovery-key').fill(recoveryKey)
    await recovered.getByRole('button',{name:'Восстановить',exact:true}).click()
    await expect(recovered.locator('[data-testid="shell-status-link"][data-session-state="online"]')).toBeVisible()
    await recovered.goto('/browser')
    await expect(recovered.getByTestId('browser-file-thumb')).toBeVisible()
    expect(await recovered.getByTestId('browser-file-thumb').evaluate(node=>(node as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
    await recovered.goto(viewerPath);await expect(recovered.getByTestId('file-viewer-image')).toBeVisible()
    await recovered.getByTestId('viewer-action-publish').click()
    await recovered.getByRole('button',{name:'Показать ссылку',exact:true}).click()
    await expect(recovered.getByTestId('public-card-published-url')).toHaveValue(url)
    await external.getByRole('button',{name:'Увеличить изображение'}).click()
    await expect(external.getByTestId('public-card-lightbox')).toBeVisible()
    await recovered.getByTestId('public-card-publication').getByRole('button',{name:'Отозвать ссылку',exact:true}).click()
    await expect(recovered.getByText(/Ссылка отозвана сервером/)).toBeVisible()
    await expect(external.getByTestId('public-card-image')).toHaveCount(0,{timeout:20000})
    await expect(external.getByTestId('public-card-lightbox')).toHaveCount(0)
    await external.reload()
    await expect(external.getByRole('heading',{name:'Карточка недоступна'})).toBeVisible()
    await expect(external.locator('main img')).toHaveCount(0)
    await page.getByRole('button',{name:'Закрыть публикацию'}).click()
    await expect(page.getByTestId('file-viewer-image')).toBeVisible()
  }finally{await owner.close();await visitor.close();await recoveredOwner.close()}
})
