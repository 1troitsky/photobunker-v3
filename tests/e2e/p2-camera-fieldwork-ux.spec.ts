import {test,expect} from '@playwright/test'

test('Fieldwork Camera 1.2: one Shell, three context actions, real modes and non-destructive blind overlay',async({page})=>{
  test.setTimeout(120000)
  await page.setViewportSize({width:390,height:844})
  await page.goto('/camera')
  await expect(page.getByTestId('camera-shell-actions')).toBeVisible()
  await expect(page.getByTestId('camera-header-flip')).toBeDisabled()
  await expect(page.getByTestId('camera-header-torch')).toBeDisabled()
  await expect(page.getByTestId('camera-header-blind')).toBeDisabled()

  await page.goto('/settings')
  await page.getByRole('button',{name:'Создать ключ'}).click()
  await page.getByLabel('Я сохранил ключ восстановления').check()
  await page.getByRole('button',{name:'Завершить регистрацию'}).click()
  await expect(page.getByText('Подтверждённая сессия')).toBeVisible()
  await page.goto('/camera')
  await expect(page.getByTestId('camera-fieldwork')).toBeVisible()
  await expect(page.locator('.shell-header')).toHaveCount(1)
  await expect(page.locator('.shell-dock')).toHaveCount(1)
  const buttons=page.getByTestId('camera-shell-actions').locator('button')
  await expect(buttons).toHaveCount(3)
  await expect(page.getByTestId('verified-plan-link')).toHaveCount(0)
  await expect(page.getByTestId('camera-mode-tabs').locator('button')).toHaveCount(3)
  await expect(page.getByTestId('camera-mode-tabs')).toHaveCSS('height','46px')
  await expect(page.getByTestId('camera-stage-controls')).toHaveCSS('min-height','124px')
  // Exact accepted shutter: black background, white ring and separate inner disc.
  const shutter=page.getByRole('button',{name:'Сделать снимок'})
  await expect(shutter).toHaveCSS('border-top-width','4px')
  await expect(shutter).toHaveCSS('background-color','rgb(16, 16, 16)')
  await expect(shutter.locator('.camera-shutter-fill')).toHaveCSS('background-color','rgb(255, 255, 255)')
  await expect(page.getByTestId('camera-gps-pill')).toBeVisible()
  // The approved bottom trio uses icons ABOVE its two context labels.
  await expect(page.getByTestId('camera-open-assignment').locator('svg')).toHaveCount(1)
  await expect(page.getByTestId('camera-open-settings').locator('svg')).toHaveCount(1)
  for(const id of ['camera-open-assignment','camera-open-settings']){
    await expect(page.getByTestId(id)).toHaveCSS('flex-direction','column')
  }
  await expect(page.getByTestId('camera-mode-tab-photo')).toHaveAttribute('aria-pressed','true')
  await expect(page.getByTestId('camera-stage')).toBeVisible()
  await expect(page.getByTestId('camera-viewfinder')).toBeVisible()
  await expect(page.getByTestId('camera-viewfinder').locator('.camera-finder-corner')).toHaveCount(4)
  await expect(page.getByTestId('camera-details')).toBeHidden()
  // The owner-approved Camera 1.2 has only three actions below the stage,
  // one mode selector (tabs), and NO P1/P2 technical destination selector.
  await expect(page.locator('.camera-device-actions')).toHaveCount(0)
  await page.getByTestId('camera-open-settings').click()
  await expect(page.locator('#camera-mode')).toHaveCount(0)
  await expect(page.locator('#camera-photo-storage')).toHaveCount(0)
  await expect(page.getByTestId('camera-permission-camera')).toBeVisible()
  await expect(page.getByTestId('camera-permission-microphone')).toBeVisible()
  await expect(page.getByTestId('camera-assignment-panel')).toBeHidden()
  await page.getByTestId('camera-grid-setting').check()
  await expect(page.getByTestId('camera-grid').locator('span')).toHaveCount(4)
  await page.getByTestId('camera-gps-visibility').uncheck()
  await expect(page.getByTestId('camera-gps-indicator')).toHaveCount(0)
  await page.getByTestId('camera-gps-visibility').check()
  await expect(page.getByTestId('camera-gps-indicator')).toBeVisible()
  await page.getByTestId('camera-grid-setting').uncheck()
  await expect(page.getByTestId('camera-grid')).toHaveCount(0)
  await page.getByTestId('camera-sheet-close').click()
  await expect(page.getByTestId('camera-details')).toBeHidden()
  // The approved GPS status is ONE pill leading into camera settings,
  // not a second inline device permission button below the viewfinder.
  await expect(page.getByTestId('camera-gps-indicator').locator('button')).toHaveCount(1)
  await page.getByTestId('camera-gps-pill').click()
  await expect(page.getByTestId('camera-settings-panel')).toBeVisible()
  await expect(page.getByTestId('camera-gps-settings-status')).toBeVisible()
  await page.getByTestId('camera-sheet-close').click()

  // Native capture still follows the visible approved mode tabs.
  await page.getByTestId('camera-mode-tab-audio').click()
  await expect(page.getByTestId('camera-mode-tab-audio')).toHaveAttribute('aria-pressed','true')
  await expect(page.getByTestId('camera-audio-view')).toBeVisible()
  await expect(page.getByTestId('camera-viewfinder').locator('.camera-finder-corner')).toHaveCount(0)
  await expect(page.getByTestId('camera-header-flip')).toBeDisabled()
  await expect(page.getByTestId('camera-header-torch')).toBeDisabled()
  await page.getByTestId('camera-header-blind').click()
  const blind=page.getByTestId('camera-blind-overlay')
  await expect(blind).toBeVisible()
  await expect(blind).toHaveCSS('position','fixed')
  await expect(blind).toHaveAttribute('aria-modal','true')
  const cover=await blind.boundingBox()
  expect(cover).toMatchObject({x:0,y:0,width:390,height:844})
  await expect(page.getByTestId('camera-blind-shutter')).toBeVisible()
  await expect(page.locator('.camera-viewfinder video')).toHaveCount(1)
  await expect(page.locator('.camera-stage-controls')).not.toBeVisible()
  await expect(page.getByTestId('camera-blind-shutter')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(blind).toHaveCount(0)
  await expect(page.getByTestId('camera-header-blind')).toBeFocused()
  await page.getByTestId('camera-header-blind').click()
  await page.getByRole('button',{name:'Вернуться назад'}).click()
  await expect(blind).toHaveCount(0)

  await page.getByTestId('camera-mode-tab-photo').click()
  await expect(page.getByTestId('camera-mode-tab-photo')).toHaveAttribute('aria-pressed','true')
  await expect(page.getByTestId('camera-header-flip')).toBeEnabled()
  await page.getByTestId('camera-open-settings').click()
  await expect(page.getByTestId('camera-settings-panel')).toHaveCSS('position','fixed')
  await expect(page.getByTestId('camera-settings-panel')).toBeInViewport()
  await expect(page.getByTestId('camera-settings-panel')).toHaveAttribute('role','dialog')
  await expect(page.getByTestId('camera-settings-panel')).toHaveAttribute('aria-modal','true')
  await expect(page.getByTestId('camera-sheet-backdrop')).toBeVisible()
  await expect(page.getByTestId('camera-sheet-close')).toBeFocused()
  await page.getByTestId('camera-sheet-close').press('Shift+Tab')
  await expect(page.getByRole('button',{name:'Готово'})).toBeFocused()
  await page.getByRole('button',{name:'Готово'}).press('Tab')
  await expect(page.getByTestId('camera-sheet-close')).toBeFocused()
  await page.getByTestId('camera-sheet-close').click()
  await expect(page.getByTestId('camera-sheet-backdrop')).toHaveCount(0)
  await expect(page.getByTestId('camera-open-settings')).toBeFocused()
  await page.getByTestId('camera-open-assignment').click()
  await expect(page.getByTestId('camera-assignment-panel')).toHaveCSS('position','fixed')
  await expect(page.getByTestId('camera-assignment-panel')).toBeInViewport()
  await expect(page.getByTestId('camera-assignment-panel')).toHaveAttribute('role','dialog')
  await expect(page.getByTestId('camera-assignment-panel')).toHaveAttribute('aria-modal','true')
  await expect(page.getByTestId('camera-assignment-finish')).toBeEnabled()
  await page.getByTestId('camera-assignment-finish').click()
  await expect(page.getByTestId('camera-sheet-backdrop')).toHaveCount(0)

  // Device capture permission may fail in CI; the UI must not invent hardware.
  // Viewfinder and E2EE forms are the same mounted instance on every screen.
  for(const width of [320,390,1280]){
    await page.setViewportSize({width,height:844})
    const header=page.locator('.shell-header')
    await expect(header).toHaveCSS('height','64px')
    expect(await header.evaluate(el=>el.scrollWidth>el.clientWidth),
      'Camera header overflow at '+width).toBe(false)
    await expect(page.getByTestId('camera-shell-actions').locator('button')).toHaveCount(3)
    await expect(page.locator('.camera-viewfinder video')).toHaveCount(1)
  }
})
