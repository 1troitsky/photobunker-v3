import {test,expect} from '@playwright/test'

test('Browser v3: five owner-approved Header actions control the real encrypted catalog',async({page,context})=>{
  test.setTimeout(150000)
  await page.setViewportSize({width:390,height:844})
  await page.goto('/browser')
  const actions=page.getByTestId('browser-shell-actions')
  await expect(actions).toBeVisible()
  await expect(actions.locator('button')).toHaveCount(5)
  await expect(page.getByTestId('browser-header-folder')).toBeDisabled()

  await page.goto('/settings')
  await page.getByRole('button',{name:'Создать ключ'}).click()
  await page.getByLabel('Я сохранил ключ восстановления').check()
  await page.getByRole('button',{name:'Завершить регистрацию'}).click()
  await expect(page.getByText('Подтверждённая сессия')).toBeVisible()
  await page.goto('/browser')
  await expect(page.getByTestId('browser-v3')).toBeVisible()
  await expect(page.getByTestId('browser-primary-sections').locator('button'))
    .toHaveCount(4)
  await expect(page.getByTestId('browser-tab-active')).toHaveAttribute('aria-pressed','true')
  await expect(page.getByTestId('browser-view-switch').locator('button'))
    .toHaveCount(3)
  const header=page.locator('.shell-header')
  await expect(header).toHaveCount(1)
  await expect(page.locator('.shell-dock')).toHaveCount(1)
  await expect(header.getByTestId('browser-shell-actions').locator('button')).toHaveCount(5)
  // The Browser body no longer duplicates its New Folder Header action.
  await expect(page.getByRole('button',{name:'Новая папка'})).toHaveCount(1)
  await expect(page.getByTestId('browser-header-folder')).toBeEnabled()
  await page.getByTestId('browser-header-folder').click()
  const folderDialog=page.getByTestId('browser-new-folder-sheet')
  await expect(folderDialog).toBeVisible()
  await expect(folderDialog).toHaveAttribute('role','dialog')
  await expect(folderDialog).toHaveAttribute('aria-modal','true')
  await expect(folderDialog).toHaveCSS('position','fixed')
  await expect(page.getByTestId('browser-new-folder-parent')).toHaveValue('')
  await expect(page.getByTestId('browser-folder-name')).toBeVisible()
  await expect(page.getByTestId('browser-folder-name')).toBeFocused()
  await page.getByTestId('browser-folder-name').fill('UX Header Folder')
  await page.getByRole('button',{name:'Создать',exact:true}).click()
  await expect(page.getByRole('button',{name:'UX Header Folder',exact:true})).toBeVisible()
  await expect(page.locator('.browser-folder-cover.is-empty')).toBeVisible()
  await expect(page.locator('.browser-folder-badge')).toBeVisible()
  await expect(page.getByTestId('browser-folder-up')).toBeDisabled()
  await page.getByRole('button',{name:'UX Header Folder',exact:true}).click()
  await expect(page.getByTestId('browser-folder-up')).toBeEnabled()
  await expect(page.locator('.browser-title .subtitle')).toContainText('Файлов: 0')
  await page.getByTestId('browser-folder-up').click()
  await expect(page.getByTestId('browser-folder-up')).toBeDisabled()
  await expect(page.locator('.browser-title .subtitle')).toContainText('Папок: 1')
  const rootFolder=page.locator('.browser-folder-item')
    .filter({has:page.getByRole('button',{name:'UX Header Folder',exact:true})})
  const rootFolderId=(await rootFolder.getAttribute('data-testid'))!
    .replace('browser-folder-','')
  await page.getByRole('button',{name:'UX Header Folder',exact:true}).click()
  await page.getByTestId('browser-header-folder').click()
  await expect(page.getByTestId('browser-new-folder-parent')).toHaveValue(rootFolderId)
  await page.getByTestId('browser-folder-name').fill('Nested UX')
  await page.getByRole('button',{name:'Создать',exact:true}).click()
  await expect(page.getByRole('button',{name:'Nested UX',exact:true})).toBeVisible()
  await page.getByTestId('browser-folder-up').click()
  await expect(page.getByTestId('browser-folder-up')).toBeDisabled()

  // The third accepted Browser v3 view is a REAL encrypted folder tree,
  // not an independent demo. Navigate nested folders without touching ACL.
  await page.getByTestId('browser-view-tree').click()
  await expect(page.getByTestId('browser-view-tree')).toHaveAttribute('aria-pressed','true')
  const rootTree=page.getByTestId('browser-tree-folder-'+rootFolderId)
  await expect(rootTree).toBeVisible()
  await expect(rootTree.locator('button.browser-tree-expand')).toHaveAttribute('aria-expanded','false')
  await rootTree.locator('button.browser-tree-expand').click()
  await expect(rootTree.locator('button.browser-tree-expand')).toHaveAttribute('aria-expanded','true')
  await page.locator('.browser-tree-select').filter({hasText:'Nested UX'}).click()
  await expect(page.locator('.browser-breadcrumb')).toContainText('Nested UX')
  await expect(page.getByTestId('browser-folder-up')).toBeEnabled()
  await page.getByTestId('browser-tree-root').click()
  await expect(page.getByTestId('browser-folder-up')).toBeDisabled()
  await page.getByTestId('browser-view-list').click()
  await expect(page.getByTestId('browser-view-list')).toHaveAttribute('aria-pressed','true')

  await page.getByTestId('browser-header-search').click()
  await expect(page.getByTestId('browser-search')).toBeFocused()
  await expect(page.getByTestId('browser-archive-preferences')).toBeHidden()
  await page.getByTestId('browser-header-settings').click()
  const settings=page.getByTestId('browser-archive-preferences')
  await expect(settings).toBeInViewport()
  await expect(settings).toHaveCSS('position','fixed')
  await expect(settings).toHaveAttribute('role','dialog')
  await expect(settings).toHaveAttribute('aria-modal','true')
  await expect(page.getByTestId('browser-settings-close')).toBeFocused()
  await expect(page.getByTestId('browser-pref-use-archive')).toBeVisible()
  await expect(page.getByTestId('browser-pref-auto-delete')).toBeVisible()
  await page.getByTestId('browser-settings-close').press('Escape')
  await expect(page.getByTestId('browser-settings-backdrop')).toHaveCount(0)
  await expect(page.getByTestId('browser-header-settings')).toBeFocused()
  await page.getByTestId('browser-header-upload').click()
  const sheet=page.getByTestId('browser-import-sheet')
  await expect(sheet).toBeVisible()
  await expect(sheet).toHaveAttribute('role','dialog')
  await expect(sheet).toHaveAttribute('aria-modal','true')
  await expect(sheet).toHaveCSS('position','fixed')
  await expect(page.getByTestId('browser-import-sheet-close')).toBeFocused()
  await expect(page.getByTestId('browser-import-backdrop')).toBeVisible()
  await page.getByTestId('browser-import-sheet-close').press('Escape')
  await expect(page.getByTestId('browser-import-backdrop')).toHaveCount(0)
  await expect(page.getByTestId('browser-header-upload')).toBeFocused()
  await page.getByTestId('browser-header-upload').click()
  await expect(sheet).toHaveCSS('position','fixed')

  // Import remains in the real encrypted Local-First outbox. Header selection
  // never creates/approves permissions or bypasses folder membership.
  await context.setOffline(true)
  await page.getByTestId('media-import-file').setInputFiles({
    name:'HEADER-UX-OFFLINE.wav',mimeType:'audio/wav',
    buffer:Buffer.alloc(8192,0x61),
  })
  const rows=page.locator('[data-testid^="browser-row-media:"]')
  await expect(rows).toHaveCount(1,{timeout:25000})
  await page.getByTestId('browser-import-sheet-close').click()
  await expect(page.getByTestId('browser-import-backdrop')).toHaveCount(0)
  await page.getByTestId('browser-tab-personal').click()
  await expect(page.getByTestId('browser-tab-personal')).toHaveAttribute('aria-pressed','true')
  await expect(rows).toHaveCount(0)
  await page.getByTestId('browser-tab-assignments').click()
  await expect(page.getByTestId('browser-assignment-catalog-scope')).toBeVisible()
  await expect(rows).toHaveCount(0)
  await page.getByTestId('browser-tab-active').click()
  await expect(rows).toHaveCount(1)
  await expect(rows.first().getByTestId('browser-item-retention'))
    .toContainText('Хранение до')
  await page.getByTestId('browser-header-settings').click()
  await page.getByTestId('browser-pref-days-left').check()
  await page.getByTestId('browser-settings-close').click()
  await expect(rows.first().getByTestId('browser-item-retention'))
    .toContainText('Осталось:')
  await page.getByTestId('browser-header-settings').click()
  await page.getByTestId('browser-pref-days-left').uncheck()
  await page.getByTestId('browser-settings-close').click()
  await expect(rows.first().getByTestId('browser-item-retention'))
    .toContainText('Хранение до')
  await expect(page.getByTestId('browser-header-select')).toBeEnabled()
  await page.getByTestId('browser-header-select').click()
  await expect(page.getByTestId('browser-header-select')).toHaveAttribute('aria-pressed','true')
  await expect(page.getByTestId('browser-selection-count')).toHaveText('Выбрано: 0')
  const selected=rows.first().locator('input[type=checkbox]')
  await expect(selected).not.toBeChecked()
  await selected.check()
  await expect(page.getByTestId('browser-selection-count')).toHaveText('Выбрано: 1')
  await page.getByTestId('browser-selection-actions').click()
  const selectionMenu=page.getByTestId('browser-selection-menu')
  await expect(selectionMenu).toHaveAttribute('role','dialog')
  await expect(selectionMenu.getByRole('button',{name:'Выбрать всё на странице'})).toBeEnabled()
  await selectionMenu.getByRole('button',{name:'Снять выделение'}).click()
  await expect(page.getByTestId('browser-selection-count')).toHaveText('Выбрано: 0')
  await selectionMenu.getByRole('button',{name:'Выбрать всё на странице'}).click()
  await expect(page.getByTestId('browser-selection-count')).toHaveText('Выбрано: 1')
  await selectionMenu.getByRole('button',{name:'Выбрать всё на странице'}).press('Escape')
  await expect(selectionMenu).toHaveCount(0)
  await expect(page.getByTestId('browser-selection-actions')).toBeFocused()
  await page.getByTestId('browser-header-select').click()
  await expect(page.getByTestId('browser-header-select')).toHaveAttribute('aria-pressed','false')
  await expect(page.getByTestId('browser-selection-toolbar')).toHaveCount(0)
  await expect(rows.first().locator('input[type=checkbox]')).toHaveCount(0)
  await page.getByTestId('browser-header-select').click()
  await expect(page.getByTestId('browser-selection-count')).toHaveText('Выбрано: 0')
  await page.getByTestId('browser-selection-cancel').click()
  await expect(page.getByTestId('browser-selection-toolbar')).toHaveCount(0)

  // All controls fit both the smallest approved mobile width and desktop;
  // only the existing single App header/dock are used.
  for(const width of [320,390,1280]){
    await page.setViewportSize({width,height:844})
    await expect(header).toHaveCSS('height','64px')
    expect(await header.evaluate(el=>el.scrollWidth>el.clientWidth),
      'Header overflow at '+width).toBe(false)
    await expect(page.getByTestId('browser-shell-actions').locator('button')).toHaveCount(5)
    const heading=page.locator('.browser-title')
    expect(await heading.evaluate(el=>el.scrollWidth>el.clientWidth),
      'Browser heading overflow at '+width).toBe(false)
    await expect(page.getByTestId('browser-view-switch').locator('button'))
      .toHaveCount(3)
  }
})
