import {expect,test} from '@playwright/test'
import {readFile} from 'node:fs/promises'

// P2 #376: real encrypted Garage cloud acceptance for a native, newly encoded
// Video Editor derivative. Independent recovered device, not shared IDB.
// Recovery Key and private plaintext never enter Playwright traces.
test.use({trace:'off',screenshot:'off',video:'off'})

test('P2 #376: real video trim → offline E2EE clip → Garage → recovered-device decoder; outsider denied',async({browser})=>{
  test.setTimeout(240_000)
  const fixture=(await readFile(new URL(
    './fixtures/p2-video-clip-215-vp8.base64',import.meta.url),'utf8')).trim()
  const ac=await browser.newContext()
  const bc=await browser.newContext()
  const cc=await browser.newContext()
  const A=await ac.newPage(),B=await bc.newPage(),C=await cc.newPage()
  let recoveryKey:string|null=null
  let downloads=0
  A.on('download',()=>downloads++)
  B.on('download',()=>downloads++)
  try{
    await A.goto('/settings')
    await A.getByRole('button',{name:'Создать ключ'}).click()
    recoveryKey=await A.locator('#generated-key').inputValue()
    expect(recoveryKey).toMatch(/^PB2\./)
    await A.getByLabel('Я сохранил ключ восстановления').check()
    await A.getByRole('button',{name:'Завершить регистрацию'}).click()
    await expect(A.getByText('Подтверждённая сессия')).toBeVisible()
    const accountA=await A.evaluate(async()=>{
      const identity=await import('/src/features/identity/application/session.ts')
      return identity.requireSession().accountId
    })

    await A.goto('/browser')
    // Input is a known, independently decodable VP8 video. The editor output,
    // ciphertext and S3 receipts MUST be generated by the actual application.
    const sourceId=await A.evaluate(async base64=>{
      const data=Uint8Array.from(atob(base64),c=>c.charCodeAt(0))
      if(data.length!==656)throw Error('qa.source_fixture_bytes')
      const digest=[...new Uint8Array(await crypto.subtle.digest('SHA-256',data))]
        .map(x=>x.toString(16).padStart(2,'0')).join('')
      if(digest!=='6e7cfe019443bb5b108d75119704b3009d91a3b54082e86864634e13e3a9131b')
        throw Error('qa.source_fixture_digest')
      const m=await import('/src/features/media/application/media-outbox.ts')
      const source=new File([data],'PRIVATE-CLIP-376-SOURCE.webm',{type:'video/webm'})
      return m.enqueueEncryptedMedia(source,undefined,{
        category:'SOURCE-PRIVATE-376',description:'NEVER-INHERIT-376',
        tags:['SOURCE-376'],
      })
    },fixture)

    await A.goto('/browser/file/media/'+sourceId)
    await A.getByTestId('viewer-action-edit').click()
    const video=A.getByTestId('file-viewer-video')
    await expect(video).toBeVisible({timeout:20_000})
    await expect.poll(()=>video.evaluate((el:HTMLVideoElement)=>el.readyState),
      {timeout:25_000}).toBeGreaterThanOrEqual(2)
    await expect(A.getByTestId('file-editor-video-selected')).toContainText('3.0 с')

    const setRange=async(id:string,value:string)=>{
      await A.getByTestId(id).evaluate((input:HTMLInputElement,raw)=>{
        const setter=Object.getOwnPropertyDescriptor(
          HTMLInputElement.prototype,'value')?.set
        if(!setter)throw Error('qa.range_setter_missing')
        setter.call(input,raw)
        input.dispatchEvent(new Event('input',{bubbles:true}))
        input.dispatchEvent(new Event('change',{bubbles:true}))
      },value)
    }
    await setRange('file-editor-video-start','0.5')
    await setRange('file-editor-video-end','2.2')
    await expect(A.getByTestId('file-editor-video-selected')).toContainText('1.7 с')

    // Lost network before exporting: NO fake sync and no OS gallery.
    await ac.setOffline(true)
    await A.getByTestId('file-editor-video-save-clip').click()
    await expect(A.getByTestId('file-editor-video-clip-status'))
      .toContainText('зашифрован',{timeout:45_000})
    await expect(A.getByTestId('file-editor-video-clip-error')).toHaveCount(0)
    const local=await A.evaluate(async originalId=>{
      const m=await import('/src/features/media/application/media-outbox.ts')
      const entries=await m.listLocalMedia()
      const original=entries.find(x=>x.mediaId===originalId)
      const derived=entries.find(x=>x.mediaId!==originalId)
      if(!derived||!original||entries.length!==2)
        throw Error('qa.clip_not_local')
      const clip=await m.readLocalMedia(derived.mediaId)
      const originalFile=await m.readLocalMedia(originalId)
      const hash=await crypto.subtle.digest('SHA-256',await clip.blob.arrayBuffer())
      const sourceHash=await crypto.subtle.digest('SHA-256',await originalFile.blob.arrayBuffer())
      const header=new Uint8Array(await clip.blob.slice(0,8).arrayBuffer())
      const containerHeaderOK=clip.blob.type==='video/mp4'
        ?header[4]===0x66&&header[5]===0x74&&header[6]===0x79&&header[7]===0x70
        :clip.blob.type==='video/webm'&&header[0]===0x1a
          &&header[1]===0x45&&header[2]===0xdf&&header[3]===0xa3
      return {
        id:derived.mediaId,bytes:clip.blob.size,mime:clip.blob.type,
        name:clip.metadata.fileName,
        digest:[...new Uint8Array(hash)].map(x=>x.toString(16).padStart(2,'0')).join(''),
        originalDigest:[...new Uint8Array(sourceHash)]
          .map(x=>x.toString(16).padStart(2,'0')).join(''),
        sourceName:originalFile.metadata.fileName,
        sourceCategory:originalFile.metadata.category,
        category:clip.metadata.category??null,
        description:clip.metadata.description??null,
        tags:clip.metadata.tags??[],
        gps:clip.metadata.gps??null,
        capture:derived.capture??null,
        localState:derived.state,containerHeaderOK,
        nameLeakedInContract:JSON.stringify(derived.contract)
          .includes('PRIVATE-CLIP-376-SOURCE'),
      }
    },sourceId)
    expect(local).toMatchObject({
      localState:'queued',containerHeaderOK:true,
      sourceName:'PRIVATE-CLIP-376-SOURCE.webm',
      sourceCategory:'SOURCE-PRIVATE-376',
      category:null,description:null,tags:[],gps:null,capture:null,
      nameLeakedInContract:false,
    })
    expect(['video/mp4','video/webm']).toContain(local.mime)
    expect(local.name).toBe('PRIVATE-CLIP-376-SOURCE-clip-500-2200.'
      +(local.mime==='video/mp4'?'mp4':'webm'))
    expect(local.bytes).toBeGreaterThan(64)
    expect(local.digest).toMatch(/^[0-9a-f]{64}$/)
    expect(local.originalDigest)
      .toBe('6e7cfe019443bb5b108d75119704b3009d91a3b54082e86864634e13e3a9131b')
    expect(downloads).toBe(0)

    // Actual authenticated signed S3 reservation, ciphertext PUT and finalize.
    await ac.setOffline(false)
    await A.evaluate(async()=>{
      const m=await import('/src/features/media/application/media-outbox.ts')
      await m.synchronizeMedia()
    })
    await expect.poll(()=>A.evaluate(async ids=>{
      const m=await import('/src/features/media/application/media-outbox.ts')
      const rows=await m.listLocalMedia()
      return ids.map(id=>rows.find(x=>x.mediaId===id)?.state??'missing')
    },[sourceId,local.id]),{timeout:45_000}).toEqual(['synced','synced'])
    const manifest=await A.evaluate(async id=>{
      const [response,list]=await Promise.all([
        fetch('/media/v1/'+id+'/manifests',{
          credentials:'same-origin',cache:'no-store',
        }),
        fetch('/media/v1',{credentials:'same-origin',cache:'no-store'}),
      ])
      const body=await response.json()
      const listing=await list.json() as {items:Array<{mediaId:string}>}
      return {
        status:response.status,indexed:listing.items.some(x=>x.mediaId===id),
        leaksName:JSON.stringify(body).includes('PRIVATE-CLIP-376-SOURCE'),
        leaksDescription:JSON.stringify(body).includes('NEVER-INHERIT-376'),
      }
    },local.id)
    expect(manifest).toEqual({
      status:200,indexed:true,leaksName:false,leaksDescription:false,
    })

    // Separate context B: new genuine device and account recovery, NO IDB
    // cloning. It must get independently signed cloud manifest/chunks.
    await B.goto('/settings')
    expect(await B.evaluate(async()=>{
      const storage=await import('/src/features/identity/infrastructure/storage.ts')
      return (await storage.listDevices()).length
    })).toBe(0)
    await B.locator('#recovery-key').fill(recoveryKey)
    await B.getByRole('button',{name:'Восстановить',exact:true}).click()
    await expect(B.getByText('Подтверждённая сессия'))
      .toBeVisible({timeout:30_000})
    const restored=await B.evaluate(async id=>{
      const identity=await import('/src/features/identity/application/session.ts')
      const session=identity.requireSession()
      const me=await fetch('/identity/v2/me',{
        credentials:'same-origin',cache:'no-store',
      })
      if(!me.ok)throw Error('qa.recovered_device_unverified')
      const server=await me.json() as {accountId:string;deviceId:string}
      if(session.accountId!==server.accountId||session.deviceId!==server.deviceId)
        throw Error('qa.recovered_device_mismatch')
      const m=await import('/src/features/media/application/media-outbox.ts')
      const localCount=(await m.listLocalMedia()).length
      const cloudIndex=await m.listCloudMedia()
      if(!cloudIndex.items.some(x=>x.mediaId===id&&x.mediaType==='video'))
        throw Error('qa.derivative_cloud_index_missing')
      const clip=await m.readCloudMedia(id)
      const hash=await crypto.subtle.digest('SHA-256',await clip.blob.arrayBuffer())
      const url=URL.createObjectURL(clip.blob)
      const video=document.createElement('video')
      video.src=url;video.preload='auto';video.muted=true;video.playsInline=true
      try{
        await new Promise<void>((resolve,reject)=>{
          const timer=setTimeout(()=>reject(Error('qa.recovered_clip_decode_timeout')),15000)
          video.onloadeddata=()=>{clearTimeout(timer);resolve()}
          video.onerror=()=>{clearTimeout(timer);reject(Error('qa.recovered_clip_not_decodable'))}
          video.load()
        })
        return {
          accountId:session.accountId,deviceId:session.deviceId,
          localCount,name:clip.metadata.fileName,
          category:clip.metadata.category??null,
          description:clip.metadata.description??null,
          gps:clip.metadata.gps??null,
          size:clip.blob.size,mime:clip.blob.type,
          digest:[...new Uint8Array(hash)]
            .map(x=>x.toString(16).padStart(2,'0')).join(''),
          width:video.videoWidth,height:video.videoHeight,
          ready:video.readyState>=HTMLMediaElement.HAVE_CURRENT_DATA,
        }
      }finally{
        video.pause();video.removeAttribute('src');video.load()
        URL.revokeObjectURL(url)
      }
    },local.id)
    expect(restored).toMatchObject({
      accountId:accountA,localCount:0,name:local.name,
      category:null,description:null,gps:null,
      size:local.bytes,mime:local.mime,digest:local.digest,
      width:32,height:32,ready:true,
    })
    await B.goto('/browser/file/media/'+local.id)
    const recoveredVideo=B.getByTestId('file-viewer-video')
    await expect(recoveredVideo).toBeVisible({timeout:30_000})
    await expect.poll(()=>recoveredVideo.evaluate((el:HTMLVideoElement)=>el.readyState),
      {timeout:30_000}).toBeGreaterThanOrEqual(2)

    // Unrelated identity C must not learn the new clip's manifest or index.
    await C.goto('/settings')
    await C.getByRole('button',{name:'Создать ключ'}).click()
    await C.getByLabel('Я сохранил ключ восстановления').check()
    await C.getByRole('button',{name:'Завершить регистрацию'}).click()
    await expect(C.getByText('Подтверждённая сессия')).toBeVisible()
    await C.evaluate(async()=>{
      const identity=await import('/src/features/identity/application/session.ts')
      await identity.reauthenticate()
    })
    const denied=await C.evaluate(async id=>{
      const [manifest,index]=await Promise.all([
        fetch('/media/v1/'+id+'/manifests',{
          credentials:'same-origin',cache:'no-store',
        }),
        fetch('/media/v1',{credentials:'same-origin',cache:'no-store'}),
      ])
      const list=await index.json() as {items:Array<{mediaId:string}>}
      return {manifestStatus:manifest.status,
        accessible:list.items.some(x=>x.mediaId===id)}
    },local.id)
    expect(denied).toEqual({manifestStatus:404,accessible:false})
    expect(downloads).toBe(0)
    // Never attach/write recoveryKey, ciphertext plaintext or per-user IDs.
  }finally{
    recoveryKey=null
    await Promise.allSettled([ac.close(),bc.close(),cc.close()])
  }
})
